"""MODEL_REPORT.md from benchmark results.

Usage: model_report.py RESULTS_DIR > MODEL_REPORT.md

RESULTS_DIR holds (in any subfolder) the files bench.yml uploads:
  bench-<variant>-<runner>.json      spotter-bench output
  tier-<variant>.summary.json        spotter-check generated --summary, model on
  tier-off.summary.json              the same with the model off (baseline)
  fixtures-<variant>.json            spotter-check fixtures --json, model on

Thresholds and the selection rule are the spec's ("Model variants and the
selection rule"); the gating runner is macos-15 (DECISIONS.md).
"""
import json
import pathlib
import re
import sys

GATING = "macos-15"
VARIANTS = ["C", "A", "B-E2B", "B-E2B-QAT", "B-E4B", "B-E4B-QAT"]
RUNNER_ORDER = ["macos-15", "macos-15-intel", "windows-2025", "macos-26", "windows-11-arm"]

# (label, key, test, shown)
THRESHOLDS = [
    ("Peak RSS ≤ 4.0 GB", lambda r: r["peak_rss_mb"] <= 4096),
    ("Load ≤ 20 s", lambda r: r["load_s"] <= 20),
    ("Latency p95 ≤ 3 s", lambda r: r["overall"]["latency_p95_s"] <= 3),
    ("False merges ≤ 1%", lambda r: r["overall"]["false_merge_rate"] <= 0.01),
    ("Accuracy ≥ 95%", lambda r: r["overall"]["accuracy_on_answered"] >= 0.95),
    ("Unsure ≤ 15%", lambda r: r["overall"]["unsure_rate"] <= 0.15),
    ("Injection 100%", lambda r: injection(r)[0] == injection(r)[1]),
]


def injection(r):
    """(right, total) over the prompt-injection questions."""
    items = [x for x in r.get("records", []) if x.get("kind") == "injection"]
    return sum(x["outcome"] == "right" for x in items), len(items)


def score(r):
    """Share of all questions answered correctly: the 'best scorer' measure."""
    o = r["overall"]
    return o["accuracy_on_answered"] * (1 - o["unsure_rate"])


def load(root):
    bench, tiers, fixtures = {}, {}, {}
    for p in pathlib.Path(root).rglob("*.json"):
        name = p.name
        try:
            data = json.loads(p.read_text(encoding="utf-8-sig"))
        except (OSError, ValueError):
            continue
        if m := re.fullmatch(r"bench-(.+)-((?:macos|windows|ubuntu)-[\w-]+)\.json", name):
            bench[(m[1], m[2])] = data
        elif m := re.fullmatch(r"tier-(.+)\.summary\.json", name):
            tiers[m[1]] = data
        elif m := re.fullmatch(r"fixtures-(.+)\.json", name):
            fixtures[m[1]] = data
        elif re.fullmatch(r"(C|A|B-E[24]B(-QAT)?)\.json", name) and "variant" in data:
            bench[(data["variant"], "local-" + data.get("os", "?"))] = data
    return bench, tiers, fixtures


def fixture_rate(rows):
    model = [r for r in rows if r.get("tier") == "model" and not r.get("skipped")]
    if not model:
        return None
    return sum(r["passed"] for r in model) / len(model), len(model)


def pct(x):
    return f"{100 * x:.1f}%"


def main():
    bench, tiers, fixtures = load(sys.argv[1] if len(sys.argv) > 1 else "results")
    runners = sorted({r for _, r in bench}, key=lambda r: (RUNNER_ORDER.index(r) if r in RUNNER_ORDER else 99, r))
    out = ["# Model report", ""]
    out.append("Generated by `tools/model_report.py` from benchmark results. Llama threads are capped at 2 everywhere; "
               "Windows runs under a 4 GB job-object memory limit. Each call that runs past 5 s counts as unsure.")
    out.append("")

    for runner in runners:
        rows = [(v, bench[(v, runner)]) for v in VARIANTS if (v, runner) in bench]
        if not rows:
            continue
        out.append(f"## {runner}" + (" (gating)" if runner == GATING else ""))
        out.append("")
        out.append("| Variant | Model file | Load | Warm-up | Peak RSS | p50 | p95 | Accuracy | False merges | Unsure | Injection | Passes |")
        out.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
        for v, r in rows:
            if "error" in r:
                out.append(f"| {v} | — | failed: {r['error']} | | | | | | | | | no |")
                continue
            o = r["overall"]
            right, total = injection(r)
            failed = [label for label, test in THRESHOLDS if not test(r)]
            out.append(
                f"| {v} | {r.get('model', '')} | {r['load_s']:.1f} s | {r.get('warm_s', 0):.1f} s | "
                f"{r['peak_rss_mb'] / 1024:.2f} GB | {o['latency_p50_s']:.2f} s | {o['latency_p95_s']:.2f} s | "
                f"{pct(o['accuracy_on_answered'])} | {pct(o['false_merge_rate'])} | {pct(o['unsure_rate'])} | "
                f"{right}/{total} | {'yes' if not failed else 'no: ' + ', '.join(failed)} |"
            )
        out.append("")
        out.append("Per task (accuracy on answered / unsure / p95):")
        out.append("")
        tasks = ["t1_same_person", "t2_same_site", "t3_cell_meaning", "t4_column_role", "t5_free_text"]
        out.append("| Variant | " + " | ".join(t.split("_", 1)[0].upper() for t in tasks) + " |")
        out.append("| --- |" + " --- |" * len(tasks))
        for v, r in rows:
            if "error" in r:
                continue
            cells = []
            for t in tasks:
                x = r["tasks"].get(t)
                cells.append("—" if not x or not x["items"] else
                             f"{pct(x['accuracy_on_answered'])} / {pct(x['unsure_rate'])} / {x['latency_p95_s']:.1f} s")
            out.append(f"| {v} | " + " | ".join(cells) + " |")
        out.append("")

    out.append("## Questions per file and model-tier fixtures")
    out.append("")
    off = tiers.get("off")
    if tiers or fixtures:
        out.append("| Variant | Questions per file | Files with none | Merges | False merges | Model-tier fixtures |")
        out.append("| --- | --- | --- | --- | --- | --- |")
        for v in ["off"] + VARIANTS:
            t = tiers.get(v)
            f = fixture_rate(fixtures.get(v, [])) if v != "off" else None
            if not t and not f:
                continue
            q = f"{t['questions_per_file']:.2f}" if t else "—"
            none = f"{t['files_without_questions']}/{t['files']}" if t else "—"
            out.append(f"| {v} | {q} | {none} | {t['merges'] if t else '—'} | {t['false_merges'] if t else '—'} | "
                       f"{pct(f[0]) + f' of {f[1]}' if f else '—'} |")
        if off:
            out.append("")
            out.append(f"Model off asks {off['questions_per_file']:.2f} questions per file; "
                       "the difference per variant is what the model is worth.")
    else:
        out.append("No end-to-end results in this run.")
    out.append("")

    out.append("## Recommendation (selection rule, gating runner)")
    out.append("")
    gating = {v: bench[(v, GATING)] for v in VARIANTS if (v, GATING) in bench and "error" not in bench[(v, GATING)]}
    if not gating:
        out.append(f"No results from the gating runner ({GATING}) yet.")
    else:
        def tier_ok(v):
            f = fixture_rate(fixtures.get(v, []))
            return f is None or f[0] >= 0.95
        passing = [v for v, r in gating.items() if all(test(r) for _, test in THRESHOLDS) and tier_ok(v)]
        if passing:
            best = min(passing, key=lambda v: gating[v]["peak_rss_mb"])
            out.append(f"**{best}**: passes every threshold; smallest peak RSS among passing variants "
                       f"({', '.join(passing)}).")
        else:
            ok = [v for v, r in gating.items() if r["overall"]["false_merge_rate"] <= 0.01 and r["peak_rss_mb"] <= 4096]
            if ok:
                best = max(ok, key=lambda v: score(gating[v]))
                out.append(f"No variant passes every threshold. Best scorer with false merges ≤ 1% and RSS ≤ 4.0 GB: "
                           f"**{best}** ({pct(score(gating[best]))} of questions answered correctly).")
                # What that pick is worth, so the rule's answer can be judged.
                o = gating[best]["overall"]
                notes = [f"it answers {pct(1 - o['unsure_rate'])} of questions (the rest go to the owner)"]
                t, off = tiers.get(best), tiers.get("off")
                if t and off:
                    notes.append(f"end to end it asks {t['questions_per_file']:.2f} questions per file against "
                                 f"{off['questions_per_file']:.2f} with the model off, with {t['false_merges']} false "
                                 f"merges against {off['false_merges']}")
                out.append("")
                out.append(f"For context on {best}: " + "; ".join(notes) + ".")
            else:
                out.append("No variant passes every threshold, and none keeps false merges ≤ 1% within 4.0 GB: "
                           "**model off**.")
        out.append("")
        out.append("Austin makes the final pick.")
    print("\n".join(out))


if __name__ == "__main__":
    main()
